"""Per-model runtime metadata, as data: outputs/runner/models.json and models.md.

    uv run python -m tar_runner.metadata [--videos 10]

For every adapter: identity and pinned revision; the switches the contract
uses (thinking, vendor sampling, context, batch invariance, HF reference
environment); the model's context length from its config; the vision tokens
one frame costs under the contract (16 frames at the 448 cap, measured with
the model's own processor over the first dev videos, whose frame sizes
vary); and the vendor's official quantized checkpoints on the Hugging Face
Hub. No GPU.
"""

from __future__ import annotations

import argparse
import json
import statistics
import urllib.parse
import urllib.request
from pathlib import Path

from . import contract
from .adapters import MODELS
from .data import REPO_ROOT, frames_for, load_rows, source_video

OUT = REPO_ROOT / "outputs" / "runner"
QUANT_WORDS = ("fp8", "fp4", "nvfp4", "awq", "gptq", "gguf", "int4", "int8", "w4a16", "w8a8",
               "mlx", "bnb", "4bit", "8bit", "quant")


def vision_tokens(adapter, videos: list[str]) -> dict:
    per_frame, sizes = [], set()
    for vid in videos:
        frames = frames_for(vid, 16, 448)
        sizes.add(frames[0].image().size)
        q = "Describe the video."
        with_f = adapter.prompt(contract.user_content(q, frames, "image_list"))
        without = adapter.prompt(contract.user_content(q, [], "image_list"))
        n = [int(adapter.processor(**adapter.hf_processor_inputs(p, fr, "image_list", source_video(vid), 16, 448))
                 ["input_ids"].shape[-1]) for p, fr in ((with_f, frames), (without, []))]
        per_frame.append((n[0] - n[1]) / 16)
    return {"mean": round(statistics.fmean(per_frame), 1), "min": round(min(per_frame), 1),
            "max": round(max(per_frame), 1), "videos": len(videos),
            "frame_sizes": sorted(f"{w}x{h}" for w, h in sizes)}


def context_length(adapter) -> int | None:
    cfg = json.loads((Path(adapter.local_dir) / "config.json").read_text())
    for c in (cfg.get("text_config") or {}, cfg.get("llm_config") or {}, cfg):
        for k in ("max_position_embeddings", "model_max_length", "seq_length"):
            if isinstance(c.get(k), int):
                return c[k]
    return None


def official_quants(adapter) -> list[str]:
    org, name = adapter.hf_id.split("/")
    stem = name.split("-Instruct")[0].split("-Reasoning")[0]
    url = ("https://huggingface.co/api/models?" +
           urllib.parse.urlencode({"author": org, "search": stem, "limit": 100}))
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            found = [m["id"] for m in json.load(r)]
    except Exception as e:  # noqa: BLE001 - a report, not a gate
        return [f"lookup failed: {e!r}"[:120]]
    return sorted(m for m in found if m != adapter.hf_id and any(w in m.lower() for w in QUANT_WORDS))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--videos", type=int, default=10)
    args = ap.parse_args()
    rows = sorted(load_rows("dev"), key=lambda r: r["priority"])
    videos = list(dict.fromkeys(r["video_id"] for r in rows))[:args.videos]

    models = {}
    for key, a in MODELS.items():
        print(f"{key} ...", flush=True)
        models[key] = {
            "hf_id": a.hf_id, "revision": a.revision,
            "input_modes": list(a.supported_modes),
            "thinking": {"mechanism": a.thinking, "modes": list(a.thinking_modes),
                         **({"kwarg": a.thinking_kwarg} if a.thinking == "template" else {}),
                         **({"instruction": a.thinking_instruction} if a.thinking == "prompt" else {})},
            "vendor_sampling": a.vendor_sampling,
            "context_length": context_length(a),
            "run_max_model_len": a.max_model_len,
            "batch_invariant": a.batch_invariant,
            "trust_remote_code": a.trust_remote_code,
            "hf_reference_env": a.hf_env,
            "vision_tokens_per_frame_16f448": vision_tokens(a, videos),
            "official_quantized_checkpoints": official_quants(a),
            "notes": a.notes,
        }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "models.json").write_text(json.dumps(models, indent=2) + "\n")

    lines = ["# Per-model runtime metadata", "",
             "Generated by `python -m tar_runner.metadata` from the adapters and each model's own "
             "processor and config. Vision tokens are per frame, 16 frames at the 448 cap, over the "
             f"first {len(videos)} dev videos.", "",
             "| Model | Vision tokens / frame (mean, range) | Context | Run context | Thinking | "
             "Batch-invariant | Vendor sampling (off / on) | Official quantized checkpoints |",
             "|---|---|---:|---:|---|---|---|---|"]
    fmt = lambda d: ", ".join(f"{k}={v}" for k, v in d.items()) if d else "—"
    for key, m in models.items():
        vt, vs = m["vision_tokens_per_frame_16f448"], m["vendor_sampling"]
        th = m["thinking"]["mechanism"] if m["thinking"]["mechanism"] != "none" else "none"
        lines.append(f"| {key} | {vt['mean']} ({vt['min']}–{vt['max']}) | {m['context_length'] or '—'} | "
                     f"{m['run_max_model_len']} | {th} | {'yes' if m['batch_invariant'] else 'no'} | "
                     f"{fmt(vs.get('off', {}))} / {fmt(vs.get('on', {}))} | "
                     f"{', '.join(m['official_quantized_checkpoints']) or 'none'} |")
    (OUT / "models.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT / 'models.json'} and models.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
